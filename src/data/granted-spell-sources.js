export function collectGrantedSpellIdsByLevel(definition, level = Number.POSITIVE_INFINITY) {
  const safeLevel = Number.isFinite(Number(level)) ? Math.max(0, Math.floor(Number(level) || 0)) : Number.POSITIVE_INFINITY;
  const grantedSpellIds = [];
  Object.entries(definition || {}).forEach(([requiredLevel, spellIds]) => {
    if (safeLevel >= Number(requiredLevel) && Array.isArray(spellIds)) {
      grantedSpellIds.push(...spellIds.filter((spellId) => typeof spellId === "string" && Boolean(spellId.trim())));
    }
  });
  return Array.from(new Set(grantedSpellIds));
}

export function flattenGrantedSpellMap(spellMap) {
  return Object.fromEntries(
    Object.entries(spellMap || {}).map(([sourceId, definition]) => [
      sourceId,
      collectGrantedSpellIdsByLevel(definition),
    ]),
  );
}
